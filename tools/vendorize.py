"""Build an isolated, pure-Python dependency tree for Sonos Controller."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys


ROOT = Path(__file__).resolve().parents[1]
# Dependencies are pip-installed here, outside the add-on, so NVDA never
# sees them in a development checkout.  Regenerate with --install.
SOURCE = ROOT / "build" / "vendor-src"
DESTINATION = ROOT / "globalPlugins" / "sonosController" / "_vendor"
MANIFEST = DESTINATION / "vendor-manifest.json"

PACKAGES = (
	"soco",
	"requests",
	"urllib3",
	"ifaddr",
	"certifi",
	"charset_normalizer",
	"idna",
)
MODULES = ("xmltodict.py", "appdirs.py")
VENDORED_ROOTS = {
	"appdirs",
	"certifi",
	"charset_normalizer",
	"idna",
	"ifaddr",
	"lxml",
	"requests",
	"soco",
	"urllib3",
	"xmltodict",
}
FORBIDDEN_OPTIONAL_ROOTS = {
	"OpenSSL",
	"aiohttp",
	"backports",
	"brotli",
	"brotlicffi",
	"chardet",
	"com",
	"cryptography",
	"h2",
	"js",
	"pyodide",
	"simplejson",
	"socks",
	"twisted",
	"win32api",
	"win32com",
}


def _read_versions() -> dict[str, str]:
	versions = {}
	for line in (ROOT / "requirements-sonos.txt").read_text(encoding="utf-8").splitlines():
		line = line.strip()
		if line and not line.startswith("#"):
			name, version = line.split("==", 1)
			versions[name.lower().replace("-", "_")] = version
	return versions


def _ignored(path: Path) -> bool:
	return (
		"__pycache__" in path.parts
		or "tests" in path.parts
		or path.name.startswith("test_")
		or path.suffix.lower() in {".pyc", ".pyo", ".pyd", ".dll", ".exe"}
	)


def _copy_runtime_tree() -> None:
	if DESTINATION.exists():
		shutil.rmtree(DESTINATION)
	DESTINATION.mkdir(parents=True)
	(DESTINATION / "__init__.py").write_text(
		'"""Private dependencies for Sonos Controller; generated by tools/vendorize.py."""\n',
		encoding="utf-8",
	)
	for name in PACKAGES:
		source = SOURCE / name
		destination = DESTINATION / name
		shutil.copytree(source, destination, ignore=lambda directory, names: [
			entry for entry in names if _ignored(Path(directory) / entry)
		])
	for name in MODULES:
		shutil.copy2(SOURCE / name, DESTINATION / name)


def _offsets(source: str) -> list[int]:
	result = [0]
	for line in source.splitlines(keepends=True):
		result.append(result[-1] + len(line))
	return result


def _rewrite_imports(path: Path) -> None:
	source = path.read_text(encoding="utf-8")
	tree = ast.parse(source)
	line_offsets = _offsets(source)
	package_depth = len(path.relative_to(DESTINATION).parent.parts)
	prefix = "." * (package_depth + 1)
	replacements: list[tuple[int, int, str]] = []
	for node in ast.walk(tree):
		if isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
			root = node.module.split(".", 1)[0]
			if root not in VENDORED_ROOTS:
				continue
			start = line_offsets[node.lineno - 1] + node.col_offset
			end = line_offsets[node.end_lineno - 1] + node.end_col_offset
			segment = source[start:end]
			rewritten = re.sub(
				r"\Afrom\s+" + re.escape(node.module) + r"(?=\s+import\b)",
				"from " + prefix + node.module,
				segment,
				count=1,
			)
			replacements.append((start, end, rewritten))
		elif isinstance(node, ast.Import):
			targets = [alias for alias in node.names if alias.name.split(".", 1)[0] in VENDORED_ROOTS]
			if not targets:
				continue
			if len(node.names) != 1:
				raise RuntimeError(f"Unsupported mixed vendor import in {path}: {ast.unparse(node)}")
			alias = targets[0]
			parts = alias.name.split(".")
			if len(parts) == 1:
				rewritten = f"from {prefix} import {parts[0]}"
				if alias.asname:
					rewritten += f" as {alias.asname}"
			elif alias.asname:
				rewritten = f"from {prefix}{'.'.join(parts[:-1])} import {parts[-1]} as {alias.asname}"
			else:
				indent = " " * node.col_offset
				rewritten = (
					f"from {prefix} import {parts[0]}\n{indent}"
					f"from {prefix}{'.'.join(parts[:-1])} import {parts[-1]}"
				)
			start = line_offsets[node.lineno - 1] + node.col_offset
			end = line_offsets[node.end_lineno - 1] + node.end_col_offset
			replacements.append((start, end, rewritten))
	for start, end, rewritten in sorted(replacements, reverse=True):
		source = source[:start] + rewritten + source[end:]
	path.write_text(source, encoding="utf-8")


def _replace(path: Path, old: str, new: str) -> None:
	source = path.read_text(encoding="utf-8")
	if old not in source:
		raise RuntimeError(f"Expected vendor source was not found in {path}: {old[:80]!r}")
	path.write_text(source.replace(old, new), encoding="utf-8")


def _patch_requests() -> None:
	compat = DESTINATION / "requests" / "compat.py"
	source = compat.read_text(encoding="utf-8")
	source = source.replace("import importlib\n", "")
	source = source.replace("from types import ModuleType\n", "")
	source = re.sub(
		r"def _resolve_char_detection\(\) -> ModuleType \| None:.*?chardet = _resolve_char_detection\(\)\n",
		"from .. import charset_normalizer as chardet\n",
		source,
		flags=re.DOTALL,
	)
	source = re.sub(
		r"# json/simplejson module import resolution\n.*?# Keep OrderedDict for backwards compatibility\.",
		"# Use the standard library JSON implementation so another add-on cannot inject simplejson.\n"
		"import json\nfrom json import JSONDecodeError\n\n"
		"# Keep OrderedDict for backwards compatibility.",
		source,
		flags=re.DOTALL,
	)
	compat.write_text(source, encoding="utf-8")

	packages = DESTINATION / "requests" / "packages.py"
	packages.write_text(
		'"""Compatibility aliases contained entirely inside the private namespace."""\n'
		"import sys\n\n"
		"from .. import idna, urllib3\n"
		"from .compat import chardet\n\n"
		"def _alias(package, public_name):\n"
		"    prefix = package.__name__\n"
		"    for module_name, module in list(sys.modules.items()):\n"
		"        if module_name == prefix or module_name.startswith(prefix + '.'):\n"
		"            suffix = module_name[len(prefix):]\n"
		"            sys.modules[f'{__name__}.{public_name}{suffix}'] = module\n\n"
		"_alias(urllib3, 'urllib3')\n"
		"_alias(idna, 'idna')\n"
		"_alias(chardet, 'charset_normalizer')\n"
		"_alias(chardet, 'chardet')\n",
		encoding="utf-8",
	)

	init = DESTINATION / "requests" / "__init__.py"
	_replace(
		init,
		"from chardet import __version__ as chardet_version  # type: ignore[import-not-found]",
		"chardet_version = None",
	)
	(DESTINATION / "requests" / "help.py").unlink(missing_ok=True)


def _patch_certifi() -> None:
	path = DESTINATION / "certifi" / "core.py"
	source = path.read_text(encoding="utf-8")
	source = source.replace('files("certifi")', "files(__package__)")
	source = source.replace('get_path("certifi", "cacert.pem")', 'get_path(__package__, "cacert.pem")')
	source = source.replace('read_text("certifi", "cacert.pem"', 'read_text(__package__, "cacert.pem"')
	path.write_text(source, encoding="utf-8")


def _patch_optional_dependencies() -> None:
	"""Disable optional integrations that could bind to another add-on's modules."""
	response = DESTINATION / "urllib3" / "response.py"
	source = response.read_text(encoding="utf-8")
	source, count = re.subn(
		r"try:\n    try:\n        import brotlicffi as brotli.*?except ImportError:\n    brotli = None\n",
		"# Do not probe another add-on's optional Brotli module.\nbrotli = None\n",
		source,
		count=1,
		flags=re.DOTALL,
	)
	if count != 1:
		raise RuntimeError("Could not disable urllib3 Brotli auto-detection")
	source, count = re.subn(
		r"try:\n    if sys\.version_info >= \(3, 14\):.*?\n\nclass MultiDecoder",
		"# Sonos Controller requests only gzip and deflate HTTP encoding.\nHAS_ZSTD = False\n\n\nclass MultiDecoder",
		source,
		count=1,
		flags=re.DOTALL,
	)
	if count != 1:
		raise RuntimeError("Could not disable urllib3 Zstandard auto-detection")
	response.write_text(source, encoding="utf-8")

	request = DESTINATION / "urllib3" / "util" / "request.py"
	source = request.read_text(encoding="utf-8")
	source, count = re.subn(
		r'ACCEPT_ENCODING = "gzip,deflate"\ntry:.*?ACCEPT_ENCODING \+= ",zstd"\n',
		'ACCEPT_ENCODING = "gzip,deflate"\n',
		source,
		count=1,
		flags=re.DOTALL,
	)
	if count != 1:
		raise RuntimeError("Could not make urllib3 Accept-Encoding deterministic")
	request.write_text(source, encoding="utf-8")

	requests_init = DESTINATION / "requests" / "__init__.py"
	source = requests_init.read_text(encoding="utf-8")
	source, count = re.subn(
		r"# Attempt to enable urllib3's fallback for SNI support.*?(?=# urllib3's DependencyWarnings)",
		"# NVDA uses the standard-library TLS implementation; do not probe PyOpenSSL.\n",
		source,
		count=1,
		flags=re.DOTALL,
	)
	if count != 1:
		raise RuntimeError("Could not disable Requests PyOpenSSL auto-detection")
	requests_init.write_text(source, encoding="utf-8")

	adapters = DESTINATION / "requests" / "adapters.py"
	source = adapters.read_text(encoding="utf-8")
	source, count = re.subn(
		r"try:\n    from \.\.urllib3\.contrib\.socks import SOCKSProxyManager.*?"
		r'def SOCKSProxyManager\(\*args: Any, \*\*kwargs: Any\) -> None:\n        raise InvalidSchema\("Missing dependencies for SOCKS support\."\)\n',
		'def SOCKSProxyManager(*args: Any, **kwargs: Any) -> None:\n'
		'    raise InvalidSchema("SOCKS proxies are not supported by Sonos Controller.")\n',
		source,
		count=1,
		flags=re.DOTALL,
	)
	if count != 1:
		raise RuntimeError("Could not disable Requests SOCKS auto-detection")
	adapters.write_text(source, encoding="utf-8")

	appdirs = DESTINATION / "appdirs.py"
	source = appdirs.read_text(encoding="utf-8")
	source, count = re.subn(
		r'#---- internal support stuff\n.*?(?=#---- self test code)',
		'#---- internal support stuff\n\n'
		'def _get_win_folder_with_ctypes(csidl_name):\n'
		'    import ctypes\n\n'
		'    csidl_const = {\n'
		'        "CSIDL_APPDATA": 26,\n'
		'        "CSIDL_COMMON_APPDATA": 35,\n'
		'        "CSIDL_LOCAL_APPDATA": 28,\n'
		'    }[csidl_name]\n'
		'    buffer = ctypes.create_unicode_buffer(1024)\n'
		'    ctypes.windll.shell32.SHGetFolderPathW(None, csidl_const, None, 0, buffer)\n'
		'    return buffer.value\n\n\n'
		'if system == "win32":\n'
		'    _get_win_folder = _get_win_folder_with_ctypes\n\n\n',
		source,
		count=1,
		flags=re.DOTALL,
	)
	if count != 1:
		raise RuntimeError("Could not make appdirs use the standard-library Windows API")
	appdirs.write_text(source, encoding="utf-8")

	for relative in (
		"soco/events_asyncio.py",
		"soco/events_twisted.py",
		"urllib3/contrib/pyopenssl.py",
		"urllib3/contrib/socks.py",
		"urllib3/http2/connection.py",
	):
		(DESTINATION / relative).unlink(missing_ok=True)
	shutil.rmtree(DESTINATION / "urllib3" / "contrib" / "emscripten", ignore_errors=True)


def _patch_soco() -> None:
	data = DESTINATION / "soco" / "data_structures_entry.py"
	_replace(data, "import lxml.etree as ET", "import re\nfrom xml.etree import ElementTree as ET")
	_replace(
		data,
		'_LOG.debug("%s imported", __name__)\n',
		'_LOG.debug("%s imported", __name__)\n\n'
		'_BARE_AMPERSAND = re.compile(r"&(?!#\\d+;|#x[0-9A-Fa-f]+;|[A-Za-z_][\\w.:-]*;)")\n\n'
		'_NUMERIC_REFERENCE = re.compile(r"&#(?:(\\d+)|x([0-9A-Fa-f]+));")\n\n'
		'def _valid_xml_codepoint(codepoint):\n'
		'    return (\n'
		'        codepoint in (9, 10, 13)\n'
		'        or 0x20 <= codepoint <= 0xD7FF\n'
		'        or 0xE000 <= codepoint <= 0xFFFD\n'
		'        or 0x10000 <= codepoint <= 0x10FFFF\n'
		'    )\n\n'
		'def _clean_numeric_reference(match):\n'
		'    codepoint = int(match.group(1) or match.group(2), 10 if match.group(1) else 16)\n'
		'    return match.group(0) if _valid_xml_codepoint(codepoint) else ""\n\n'
		'def _clean_xml_text(value):\n'
		'    """Repair the two malformed DIDL patterns seen from Sonos services."""\n'
		'    value = "".join(\n'
		'        character for character in value\n'
		'        if _valid_xml_codepoint(ord(character))\n'
		'    )\n'
		'    value = _NUMERIC_REFERENCE.sub(_clean_numeric_reference, value)\n'
		'    return _BARE_AMPERSAND.sub("&amp;", value)\n\n'
		'def _parse_xml(value):\n'
		'    try:\n'
		'        return ET.fromstring(value.encode("utf-8"))\n'
		'    except (ET.ParseError, UnicodeEncodeError) as first_error:\n'
		'        cleaned = _clean_xml_text(value)\n'
		'        if cleaned == value:\n'
		'            raise DIDLMetadataError("Could not parse DIDL-Lite metadata") from first_error\n'
		'        try:\n'
		'            return ET.fromstring(cleaned.encode("utf-8"))\n'
		'        except (ET.ParseError, UnicodeEncodeError) as error:\n'
		'            raise DIDLMetadataError("Could not parse DIDL-Lite metadata") from error\n\n',
	)
	_replace(
		data,
		'    parser = ET.XMLParser(recover=True, encoding="utf-8")\n    root = ET.fromstring(string.encode("utf-8"), parser=parser)',
		"    root = _parse_xml(string)",
	)

	zone = DESTINATION / "soco" / "zonegroupstate.py"
	_replace(zone, "from lxml import etree as LXML", "from xml.etree import ElementTree as ET")
	source = zone.read_text(encoding="utf-8")
	source = re.sub(
		r'ZGS_XSLT = """.*?ZGS_TRANSFORM = LXML\.XSLT\(LXML\.fromstring\(ZGS_XSLT\)\).*?\n',
		"",
		source,
		flags=re.DOTALL,
	)
	source = source.replace("normalized_zgs = str(tree)", 'normalized_zgs = ET.tostring(tree, encoding="unicode")')
	source = re.sub(
		r"def normalize_zgs_xml\(xml\):.*\Z",
		'def _normalize_zgs_element(element):\n'
		'    # The upstream XSLT copies attributes and child elements, discards text,\n'
		'    # and stably sorts every level by Coordinator or UUID.\n'
		'    element.text = None\n'
		'    children = list(element)\n'
		'    for child in children:\n'
		'        child.tail = None\n'
		'        _normalize_zgs_element(child)\n'
		'    children.sort(key=lambda child: child.attrib.get("Coordinator") or child.attrib.get("UUID") or "")\n'
		'    element[:] = children\n\n\n'
		'def normalize_zgs_xml(xml):\n'
		'    """Normalize a ZoneGroupState payload with the Python standard library."""\n'
		'    tree = ET.fromstring(xml)\n'
		'    _normalize_zgs_element(tree)\n'
		'    return tree\n',
		source,
		flags=re.DOTALL,
	)
	for old, new in (
		('config.EVENTS_MODULE.__name__ == "soco.events"', 'config.EVENTS_MODULE.__name__.endswith(".events")'),
		('config.EVENTS_MODULE.__name__ == "soco.events_asyncio"', 'config.EVENTS_MODULE.__name__.endswith(".events_asyncio")'),
		('config.EVENTS_MODULE.__name__ == "soco.events_twisted"', 'config.EVENTS_MODULE.__name__.endswith(".events_twisted")'),
	):
		source = source.replace(old, new)
	zone.write_text(source, encoding="utf-8")

	plugins = DESTINATION / "soco" / "plugins" / "__init__.py"
	_replace(
		plugins,
		"        modname = \".\".join(parts[:-1])\n        clsname = parts[-1]\n\n        mod = importlib.import_module(modname)",
		'        modname = ".".join(parts[:-1])\n'
		'        clsname = parts[-1]\n'
		'        if modname == "soco" or modname.startswith("soco."):\n'
		'            root = __package__.rsplit(".plugins", 1)[0]\n'
		'            modname = root + modname[4:]\n\n'
		'        mod = importlib.import_module(modname)',
	)


def _copy_licenses() -> None:
	destination = DESTINATION / "_licenses"
	destination.mkdir()
	versions = _read_versions()
	for distribution in sorted(SOURCE.glob("*.dist-info")):
		key = distribution.name.split("-", 1)[0].lower().replace("-", "_")
		if key not in versions or key == "lxml":
			continue
		target = destination / distribution.name
		for path in distribution.rglob("*"):
			if path.is_file() and ("license" in path.name.lower() or "notice" in path.name.lower() or "authors" in path.name.lower()):
				output = target / path.relative_to(distribution)
				output.parent.mkdir(parents=True, exist_ok=True)
				shutil.copy2(path, output)


def _audit_imports() -> None:
	errors = []
	for path in DESTINATION.rglob("*.py"):
		source = path.read_text(encoding="utf-8")
		tree = ast.parse(source)
		parents = {child: parent for parent in ast.walk(tree) for child in ast.iter_child_nodes(parent)}

		def under_type_checking(node):
			child = node
			parent = parents.get(child)
			while parent is not None:
				if isinstance(parent, ast.If) and child in parent.body:
					test = ast.unparse(parent.test)
					if test in {"TYPE_CHECKING", "typing.TYPE_CHECKING"}:
						return True
				child, parent = parent, parents.get(parent)
			return False

		for node in ast.walk(tree):
			if isinstance(node, ast.Import):
				for alias in node.names:
					root = alias.name.split(".", 1)[0]
					if root in VENDORED_ROOTS | FORBIDDEN_OPTIONAL_ROOTS:
						errors.append(f"{path}:{node.lineno}: {ast.unparse(node)}")
					elif root not in sys.stdlib_module_names and not under_type_checking(node):
						errors.append(f"{path}:{node.lineno}: undeclared external import {alias.name}")
			elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
				root = node.module.split(".", 1)[0]
				if root in VENDORED_ROOTS | FORBIDDEN_OPTIONAL_ROOTS:
					errors.append(f"{path}:{node.lineno}: {ast.unparse(node)}")
				elif root not in sys.stdlib_module_names and not under_type_checking(node):
					errors.append(f"{path}:{node.lineno}: undeclared external import {node.module}")
			elif isinstance(node, ast.Call) and node.args:
				name = node.func.id if isinstance(node.func, ast.Name) else node.func.attr if isinstance(node.func, ast.Attribute) else ""
				if name in {"import_module", "__import__"} and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
					if node.args[0].value.split(".", 1)[0] in VENDORED_ROOTS | FORBIDDEN_OPTIONAL_ROOTS:
						errors.append(f"{path}:{node.lineno}: dynamic import {node.args[0].value}")
	if list(DESTINATION.rglob("*.pyd")) or list(DESTINATION.rglob("*.dll")) or list(DESTINATION.rglob("*.exe")):
		errors.append("Native binaries are not allowed in the private vendor tree")
	if (DESTINATION / "lxml").exists():
		errors.append("lxml must not be present in the private vendor tree")
	if errors:
		raise RuntimeError("Vendor isolation audit failed:\n" + "\n".join(errors))


def _hashes() -> dict[str, str]:
	def content(path):
		data = path.read_bytes()
		try:
			text = data.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
		except UnicodeDecodeError:
			return data
		return text.encode("utf-8")

	return {
		path.relative_to(DESTINATION).as_posix(): hashlib.sha256(content(path)).hexdigest()
		for path in sorted(DESTINATION.rglob("*"))
		if path.is_file() and path != MANIFEST and not _ignored(path)
	}


def build() -> None:
	_copy_runtime_tree()
	_patch_soco()
	for package in PACKAGES:
		for path in (DESTINATION / package).rglob("*.py"):
			_rewrite_imports(path)
	_patch_requests()
	_patch_certifi()
	_patch_optional_dependencies()
	_copy_licenses()
	_audit_imports()
	payload = {
		"format": 1,
		"sourceVersions": _read_versions(),
		"patches": [
			"namespace all bundled imports",
			"remove optional foreign chardet and simplejson imports",
			"keep requests compatibility aliases inside the private namespace",
			"resolve certifi resources through its generated package name",
			"disable optional global HTTP integrations and use the standard-library Windows folder API",
			"remove unused asyncio and Twisted event backends",
			"replace lxml DIDL parsing and ZoneGroupState normalization",
			"make SoCo event and plugin module names namespace-safe",
		],
		"files": _hashes(),
	}
	MANIFEST.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")


def check() -> None:
	if not MANIFEST.exists():
		raise RuntimeError("Run tools/vendorize.py before building the add-on")
	payload = json.loads(MANIFEST.read_text(encoding="utf-8"))
	if payload.get("sourceVersions") != _read_versions():
		raise RuntimeError("Vendor versions do not match requirements-sonos.txt")
	if payload.get("files") != _hashes():
		raise RuntimeError("Generated vendor tree differs from vendor-manifest.json")
	_audit_imports()


def main() -> None:
	parser = argparse.ArgumentParser()
	parser.add_argument("--check", action="store_true")
	args = parser.parse_args()
	check() if args.check else build()


if __name__ == "__main__":
	main()
